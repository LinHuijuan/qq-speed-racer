export function getTrackLayout(id: TrackLayoutId): TrackLayout {
  return TRACK_LAYOUTS.find((t) => t.id === id) ?? TRACK_LAYOUTS[0];
}

export function layoutToCurve(layout: TrackLayout): THREE.CatmullRomCurve3 {
  const points = layout.points.map(([x, y, z]) => new THREE.Vector3(x, y, z));
  return new THREE.CatmullRomCurve3(points, true, 'catmullrom', layout.tension ?? 0.35);
}
